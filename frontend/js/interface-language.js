  function apply(root) {
    const scope = root || document;

    scope.querySelectorAll("[data-ui-text]").forEach((element) => {
      let params = {};
      if (element.dataset.uiTextParams) {
        try {
          params = JSON.parse(element.dataset.uiTextParams);
        } catch {
          params = {};
        }
      }
      element.textContent = t(element.dataset.uiText, params);
    });

    scope.querySelectorAll("[data-ui-placeholder]").forEach((element) => {
      const value = t(element.dataset.uiPlaceholder);
      element.setAttribute("placeholder", value);
      if (element.hasAttribute("data-placeholder")) {
        element.setAttribute("data-placeholder", value);
      }
    });

    scope.querySelectorAll("[data-ui-title]").forEach((element) => {
      element.setAttribute("title", t(element.dataset.uiTitle));
    });

    scope.querySelectorAll("[data-ui-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", t(element.dataset.uiAriaLabel));
    });

    const autoText = AUTO_TEXT[currentLocale] || {};
    if (Object.keys(autoText).length) {
      const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT);
      const nodes = [];

      while (walker.nextNode()) {
        nodes.push(walker.currentNode);
      }

      nodes.forEach((node) => {
        const original = node.nodeValue;
        const trimmed = original.trim();
        if (!trimmed || !autoText[trimmed]) return;
        node.nodeValue = original.replace(trimmed, autoText[trimmed]);
      });
    }
  }

  function applyStoredLocale() {
    if (appliedStoredLocale || !document.body) return;
    appliedStoredLocale = true;
    document.documentElement.lang = currentLocale;
    apply(document);
  }

  async function init() {
    if (initPromise) return initPromise;

    initPromise = (async () => {
      const token = localStorage.getItem("token");
      if (!token) {
        apply(document);
        return currentLocale;
      }

      try {
        const user = await getCurrentUser();
        setLocaleFromUser(user);
      } catch (error) {
        console.error("Interface language load error:", error);
      }

      apply(document);
      return currentLocale;
    })();

    return initPromise;
  }

